/**
 * Writes packages/ui/src/gallery-console.css: the Control Center's size scale,
 * scoped to `.bs-gallery-console`, for the design-system gallery ONLY.
 *
 * WHY. The gallery lives in the dashboard, which loads prototype.css, and
 * prototype.css redefines the size scale on `:root` at 0.88 (D-484). The
 * Control Center does not load prototype.css, so it renders at tokens.css's
 * 1.0 values. To show both looks side by side on one page, the console half of
 * each gallery section sits inside `.bs-gallery-console`, which puts back the
 * tokens.css value of every custom property prototype.css overrides on `:root`.
 *
 * Generated, never hand-edited: tests/unit/style-gallery-console.test.ts fails
 * if this file and the generator's output differ. Run `pnpm style:gallery`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
export const OUTPUT = 'packages/ui/src/gallery-console.css';

function rootBlocks(css: string): string[] {
  const out: string[] = [];
  for (const match of css.matchAll(/^:root \{\n([\s\S]*?)^\}/gm)) out.push(match[1]!);
  return out;
}

function definitions(block: string): Map<string, string> {
  return new Map(
    [...block.matchAll(/^\s*(--[a-z0-9-]+):\s*([^;]+);/gm)].map((m) => [m[1]!, m[2]!.trim()]),
  );
}

export function generate(root = ROOT): string {
  const tokens = readFileSync(path.join(root, 'packages/ui/src/tokens.css'), 'utf8');
  const prototype = readFileSync(path.join(root, 'packages/ui/src/prototype.css'), 'utf8');
  const base = definitions(rootBlocks(tokens)[0]!);
  const overridden = new Set(rootBlocks(prototype).flatMap((b) => [...definitions(b).keys()]));
  const lines = [...overridden]
    .filter((name) => base.has(name))
    .sort()
    .map((name) => `  ${name}: ${base.get(name)};`);
  return [
    '/*',
    ' * GENERATED by scripts/style/gallery-console.ts — do not edit by hand.',
    ' *',
    " * The Control Center's size scale (tokens.css, 1.0) for the console half of",
    ' * the design-system gallery. Loaded only by the gallery routes.',
    ' */',
    '.bs-gallery-console {',
    ...lines,
    '}',
    '',
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  writeFileSync(path.join(ROOT, OUTPUT), generate());
  console.log(`Wrote ${OUTPUT}`);
}
