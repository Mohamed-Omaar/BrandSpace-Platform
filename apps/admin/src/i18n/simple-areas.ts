export function areaCopy(locale: string) {
  const table: Copy = locale === 'ar' ? ar : en;
  return (key: AreaCopyKey, values: Record<string, string | number> = {}): string =>
    table[key].replace(/\{(\w+)\}/g, (match, name: string) =>
      name in values ? String(values[name]) : match,
    );
}

